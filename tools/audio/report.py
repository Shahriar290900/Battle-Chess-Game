"""Numeric analysis of the shipped MP3s (decoded with ffmpeg-static) -> docs/audio/sfx-report.md"""
import json, os, subprocess, sys, tempfile
import numpy as np
from scipy.io import wavfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dsp

ffmpeg = sys.argv[1]
root = os.path.abspath(os.path.join(dsp.HERE, '..', '..'))
sfx = os.path.join(root, 'public', 'audio', 'sfx')
man = json.load(open(os.path.join(sfx, 'manifest.json')))
rows, seen = [], set()
tmp = tempfile.mkdtemp()
for key, e in man['entries'].items():
    for f in e['files']:
        if f in seen:
            continue
        seen.add(f)
        wav = os.path.join(tmp, f + '.wav')
        subprocess.run([ffmpeg, '-v', 'error', '-y', '-i', os.path.join(sfx, f), '-ac', '1', '-ar', '44100', '-c:a', 'pcm_f32le', wav], check=True)
        sr, x = wavfile.read(wav)
        x = x.astype(np.float64)
        pk = np.max(np.abs(x))
        rms = np.sqrt(np.mean(x ** 2))
        n = min(len(x), 2 ** 17)
        sp = np.abs(np.fft.rfft(x[:n] * np.hanning(n)))
        fr = np.fft.rfftfreq(n, 1 / sr)
        cen = (sp * fr).sum() / (sp.sum() + 1e-12)
        low = (sp[fr < 150] ** 2).sum() / ((sp ** 2).sum() + 1e-12)
        a = np.abs(x)
        ip = int(np.argmax(a))
        i10 = int(np.argmax(a > 0.1 * pk))
        att = (ip - i10) / sr * 1000
        rows.append(dict(key=key, file=f, dur=len(x) / sr, pk=20 * np.log10(pk + 1e-12), rms=20 * np.log10(rms + 1e-12),
                         lufs=dsp.momentary_lufs_max(x), cen=cen, low=100 * low, att=att, kb=os.path.getsize(os.path.join(sfx, f)) / 1024,
                         crest=20 * np.log10(pk / (rms + 1e-12))))
rows.sort(key=lambda r: r['file'])
tot = sum(r['kb'] for r in rows)
L = np.array([r['lufs'] for r in rows])
out = [f"# SFX analysis report\n\nGenerated by `tools/audio/report.py` from the shipped MP3s (decoded). {len(rows)} files, {tot/1024:.2f} MB total.\n",
       "Columns: **Dur** seconds; **Peak/RMS** dBFS; **LUFS-M** = maximum 400 ms K-weighted loudness (the consistency target; sustained categories -14, steps/UI/debris lower by design and compensated by the manifest gain);",
       "**Centroid** spectral centroid Hz; **<150 Hz** share of spectral energy below 150 Hz (sub weight); **Attack** ms from 10 % to peak (smaller = sharper transient); **Crest** peak-RMS dB.\n",
       "| File | Dur | Peak | RMS | LUFS-M | Centroid | <150 Hz | Attack | Crest | KB |", "|---|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    out.append(f"| {r['file']} | {r['dur']:.2f} | {r['pk']:.1f} | {r['rms']:.1f} | {r['lufs']:.1f} | {r['cen']:.0f} | {r['low']:.0f}% | {r['att']:.1f} | {r['crest']:.1f} | {r['kb']:.0f} |")
hits = [r for r in rows if r['file'].startswith(('hit_', 'shatter_', 'impact_', 'clash_', 'check', 'mate', 'summon', 'spell', 'drop_', 'kneel', 'castle'))]
out.append("\n## Summary\n")
out.append(f"- Hit-class files ({len(hits)}): median attack {np.median([r['att'] for r in hits]):.1f} ms, median sub (<150 Hz) share {np.median([r['low'] for r in hits]):.0f} %, median centroid {np.median([r['cen'] for r in hits]):.0f} Hz.")
out.append(f"- Peak range: {min(r['pk'] for r in rows):.1f} to {max(r['pk'] for r in rows):.1f} dBFS (ceiling -1 dBFS before MP3 re-quantisation).")
out.append(f"- LUFS-M of hit-class files: min {min(r['lufs'] for r in hits):.1f}, max {max(r['lufs'] for r in hits):.1f}, std {np.std([r['lufs'] for r in hits]):.2f} dB.")
open(os.path.join(root, 'docs', 'audio', 'sfx-report.md'), 'w').write('\n'.join(out) + '\n')
print('report written', len(rows), 'files')
